import {chromium, expect} from '@playwright/test';
import {mkdir, copyFile} from 'node:fs/promises';
const out = new URL('../../docs/media/', import.meta.url).pathname;
await mkdir(out,{recursive:true});
const browser = await chromium.launch();
const context = await browser.newContext({viewport:{width:1280,height:720},reducedMotion:'reduce',recordVideo:{dir:out+'raw',size:{width:1280,height:720}}});
const page=await context.newPage();
const start=Date.now();
const until=async seconds=>{const ms=seconds*1000-(Date.now()-start);if(ms>0)await page.waitForTimeout(ms);};
try {
 await page.goto('http://127.0.0.1:5173/');
 await page.getByLabel('Username',{exact:true}).fill('admin');
 await page.getByLabel('Password',{exact:true}).fill('demo-admin');
 await until(4);
 await page.getByRole('button',{name:'Sign in',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Incident command',exact:true})).toBeVisible();
 await until(10);
 await page.screenshot({path:out+'incidentiq-dashboard.jpg',type:'jpeg',quality:85});
 await until(16);
 await page.getByRole('button',{name:'Declare incident',exact:true}).click();
 let dialog=page.getByRole('dialog');
 await dialog.getByLabel('Incident title').fill('Payment API connection pool timeout');
 await dialog.getByLabel('Affected service').selectOption('payments');
 await dialog.getByLabel('Description').fill('Synthetic walkthrough: payment requests time out while database connections are exhausted.');
 await dialog.getByLabel('Initial log evidence').fill('ERROR connection pool timeout trace=demo-payment-01\nWARN database connection acquisition exceeded 30000ms');
 await until(28);
 await dialog.getByRole('button',{name:'Declare incident',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Payment API connection pool timeout',exact:true})).toBeVisible();
 dialog=page.getByRole('dialog');
 await until(35);
 await dialog.getByRole('button',{name:'Acknowledged',exact:true}).click();
 await dialog.getByLabel('Response note').fill('Acknowledged. Checking connection pool pressure and recent changes.');
 await dialog.getByRole('button',{name:'Save response'}).click();
 await expect(dialog.locator('.drawer-badges')).toContainText('Acknowledged');
 await until(43);
 await dialog.getByRole('button',{name:'Investigating',exact:true}).click();
 await dialog.getByLabel('Response note').fill('Investigating synthetic database timeout evidence.');
 await dialog.getByRole('button',{name:'Save response'}).click();
 await expect(dialog.locator('.drawer-badges')).toContainText('Investigating');
 await until(49);
 await dialog.getByRole('tab',{name:'AI investigation'}).click();
 await dialog.getByRole('button',{name:'Generate analysis'}).click();
 await expect(dialog.getByRole('heading',{name:'Possible root causes'})).toBeVisible({timeout:60000});
 await until(57);
 await page.screenshot({path:out+'incidentiq-analysis.jpg',type:'jpeg',quality:85});
 await until(65);
 await dialog.getByRole('button',{name:'Resolved',exact:true}).click();
 await dialog.getByLabel('Response note').fill('Walkthrough resolved after reviewing the evidence. No production systems were changed.');
 await dialog.getByRole('button',{name:'Save response'}).click();
 await expect(dialog.locator('.drawer-badges')).toContainText('Resolved');
 await until(73);
 await dialog.getByRole('button',{name:'Close dialog',exact:true}).click();
 await until(82);
} finally {
 const video=page.video();
 await context.close();
 if(video)await copyFile(await video.path(),out+'incidentiq-walkthrough.webm');
}
const frameContext=await browser.newContext({viewport:{width:1440,height:1000},reducedMotion:'reduce'});
const frame=await frameContext.newPage();
await frame.goto('http://127.0.0.1:8000/');
await frame.locator('#try-coffee-sample').click({timeout:30000});
await expect(frame.locator('#approve-media')).toBeVisible({timeout:30000});
await frame.screenshot({path:out+'frameforge-dashboard.jpg',type:'jpeg',quality:85});
await frameContext.close();
await browser.close();
